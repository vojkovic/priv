#include <stdio.h>
#include <stdlib.h>
#include <string.h>

/* turns translations/<lang>.po into the tables in i18n.h */

#define MAX_LANGS 128
#define MAX_IDS 512

struct entry {
	char *id, *str;
};

struct lang {
	char code[32], name[128];
	int rtl;
	struct entry *entries;
	size_t n;
};

static struct lang langs[MAX_LANGS];
static size_t nlangs;
static char *ids[MAX_IDS];
static size_t nids;

static void *
grow(void *p, size_t n)
{
	void *r = realloc(p, n);

	if (!r) {
		fprintf(stderr, "po2c: out of memory\n");
		exit(1);
	}
	return r;
}

/* appends the contents of one "quoted" po string to *out */
static void
unquote(const char *s, char **out, size_t *len)
{
	const char *p = strchr(s, '"');

	if (!p)
		return;
	for (p++; *p && *p != '"'; p++) {
		char c = *p;
		if (c == '\\' && p[1]) {
			c = *++p;
			c = c == 'n' ? '\n' : c == 't' ? '\t' : c;
		}
		*out = grow(*out, *len + 2);
		(*out)[(*len)++] = c;
		(*out)[*len] = 0;
	}
}

static void
header(struct lang *l, const char *h)
{
	const char *line, *end;

	for (line = h; *line; line = *end ? end + 1 : end) {
		end = line + strcspn(line, "\n");
		if (!strncmp(line, "Language: ", 10))
			snprintf(l->code, sizeof(l->code), "%.*s", (int)(end - line - 10), line + 10);
		else if (!strncmp(line, "X-Name: ", 8))
			snprintf(l->name, sizeof(l->name), "%.*s", (int)(end - line - 8), line + 8);
		else if (!strncmp(line, "X-Direction: rtl", 16))
			l->rtl = 1;
	}
}

static void
add(struct lang *l, char *id, char *str)
{
	size_t i;

	if (!*id) {
		header(l, str ? str : "");
		free(id);
		free(str);
		return;
	}
	l->entries = grow(l->entries, (l->n + 1) * sizeof(*l->entries));
	l->entries[l->n].id = id;
	l->entries[l->n++].str = str;
	for (i = 0; i < nids && strcmp(ids[i], id); i++)
		;
	if (i == nids) {
		if (nids == MAX_IDS) {
			fprintf(stderr, "po2c: too many messages\n");
			exit(1);
		}
		ids[nids++] = id;
	}
}

static void
read_po(const char *path)
{
	struct lang *l = &langs[nlangs++];
	char line[4096], *id = NULL, *str = NULL, **cur = NULL;
	size_t idlen = 0, slen = 0, *curlen = NULL;
	FILE *f = fopen(path, "r");

	if (!f) {
		fprintf(stderr, "po2c: cannot read %s\n", path);
		exit(1);
	}
	while (fgets(line, sizeof(line), f)) {
		if (!strncmp(line, "msgid ", 6)) {
			if (id)
				add(l, id, str);
			else
				free(str);
			id = grow(NULL, 1);
			*id = 0;
			str = NULL;
			idlen = slen = 0;
			cur = &id;
			curlen = &idlen;
			unquote(line + 6, cur, curlen);
		} else if (!strncmp(line, "msgstr ", 7)) {
			free(str);
			str = grow(NULL, 1);
			*str = 0;
			cur = &str;
			curlen = &slen;
			unquote(line + 7, cur, curlen);
		} else if (line[0] == '"' && cur) {
			unquote(line, cur, curlen);
		}
	}
	if (id)
		add(l, id, str);
	else
		free(str);
	fclose(f);
	if (!*l->code || !*l->name) {
		fprintf(stderr, "po2c: %s needs Language and X-Name in its header\n", path);
		exit(1);
	}
}

static int
by_string(const void *a, const void *b)
{
	return strcmp(*(char *const *)a, *(char *const *)b);
}

static int
by_code(const void *a, const void *b)
{
	return strcmp(((const struct lang *)a)->code, ((const struct lang *)b)->code);
}

static void
literal(const char *s)
{
	putchar('"');
	for (; *s; s++) {
		if (*s == '"' || *s == '\\')
			printf("\\%c", *s);
		else if (*s == '\n')
			printf("\\n");
		else
			putchar(*s);
	}
	putchar('"');
}

static const char *
lookup(const struct lang *l, const char *id)
{
	size_t i;

	for (i = 0; i < l->n; i++)
		if (!strcmp(l->entries[i].id, id))
			return l->entries[i].str && *l->entries[i].str ? l->entries[i].str : NULL;
	return NULL;
}

int
main(int argc, char **argv)
{
	size_t i, k;
	char *p;

	if (argc < 2 || argc - 1 > MAX_LANGS) {
		fprintf(stderr, "usage: po2c file.po...\n");
		return 1;
	}
	for (i = 1; i < (size_t)argc; i++)
		read_po(argv[i]);
	qsort(ids, nids, sizeof(*ids), by_string);
	qsort(langs, nlangs, sizeof(*langs), by_code);

	printf(
	    "/* generated by tools/po2c from translations/<lang>.po */\n\n#include <stddef.h>\n\n#include \"core/i18n.h\"\n\n");
	printf("const char *const msgids[] = {\n");
	for (i = 0; i < nids; i++) {
		printf("\t");
		literal(ids[i]);
		printf(",\n");
	}
	printf("};\n\nconst size_t nmsgids = %zu;\n", nids);
	for (k = 0; k < nlangs; k++) {
		printf("\nstatic const char *const t_%s[] = {\n", langs[k].code);
		for (i = 0; i < nids; i++) {
			const char *s = lookup(&langs[k], ids[i]);
			printf("\t");
			if (s)
				literal(s);
			else
				printf("NULL");
			printf(",\n");
		}
		printf("};\n");
	}
	printf("\nconst struct ui_lang ui_langs[] = {\n");
	for (k = 0; k < nlangs; k++) {
		char tag[32];
		snprintf(tag, sizeof(tag), "%s", langs[k].code);
		for (p = tag; *p; p++)
			if (*p == '_')
				*p = '-';
		printf("\t{\"%s\", \"%s\", ", langs[k].code, tag);
		literal(langs[k].name);
		printf(", %d, t_%s},\n", langs[k].rtl, langs[k].code);
	}
	printf("};\n\nconst size_t nui_langs = %zu;\n", nlangs);
	return 0;
}
